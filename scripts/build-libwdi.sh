#!/usr/bin/env bash
# build-libwdi.sh -- build a static libwdi.a for the automatic WinUSB install.
#
# libwdi (LGPL-2.1-or-later, https://github.com/pbatard/libwdi) is the library
# Zadig is built on. It has no CMake build, so this script builds it with the
# same MinGW-w64 GCC used for the rest of the project, for WinUSB on 64-bit
# Windows 10/11, WITHOUT the Windows Driver Kit.
#
# Three small, documented changes are applied (also kept as diffs in
# third_party/libwdi-patches/ for the record; the LGPL is satisfied by shipping
# this script and the patched source, and by keeping the program relinkable):
#   1. winusb.inf.in  -- drop the co-installer / SourceDisks sections. On
#      Windows 10/11 WinUSB is an inbox driver and needs no co-installer, so
#      the WDK redistributables are not required.
#   2. winusb.cat.in  -- the catalogue then covers only the .inf.
#   3. libwdi.c       -- wdi_is_driver_supported(WDI_WINUSB) returns TRUE
#      (upstream returns FALSE unless built against the WDK). WinUSB is inbox
#      on every OS this targets, so TRUE is correct.
#
# Usage:
#   scripts/build-libwdi.sh [--clone] [SRC_DIR] [TAG]
#     --clone    git clone the tag into SRC_DIR first (needs git + network)
#     SRC_DIR    libwdi source tree (default: external/libwdi)
#     TAG        libwdi tag to build  (default: v1.5.1)
#
# On success it prints the two values to pass to CMake:
#   -DSDI_WITH_LIBWDI=ON -DLIBWDI_INCLUDE_DIR=<...> -DLIBWDI_LIBRARY=<...>
set -euo pipefail

CLONE=0
if [ "${1:-}" = "--clone" ]; then CLONE=1; shift; fi
SRC="${1:-external/libwdi}"
TAG="${2:-v1.5.1}"
CC="${CC:-gcc}"

if [ "$CLONE" = "1" ]; then
    rm -rf "$SRC"
    git clone --depth 1 --branch "$TAG" https://github.com/pbatard/libwdi.git "$SRC"
elif [ -d "$SRC/.git" ]; then
    git -C "$SRC" checkout -- .            # start from a pristine tree
fi

cd "$SRC/libwdi"
L=.                                         # the libwdi/ source directory
CFG="../mingw"                              # holds our config.h
mkdir -p "$CFG/userdir"
USERDIR_WIN="$(cd "$CFG/userdir" && pwd -W)"

# --- config.h: WinUSB only, 64-bit, no WDK; USER_DIR satisfies embedder.h -----
cat > "$CFG/config.h" <<EOF
/* Generated by scripts/build-libwdi.sh -- do not edit. WinUSB only, 64-bit,
 * no WDK (inbox WinUSB on Windows 10/11). USER_DIR points at an empty folder
 * only to satisfy embedder.h's "at least one driver directory" check. */
#pragma once
#define _GNU_SOURCE
#define WDF_VER 1011
#define OPT_M64
#define ENABLE_LOGGING 1
#define INCLUDE_DEBUG_LOGGING 1
#define USER_DIR "$USERDIR_WIN"
EOF

# --- patch 1: winusb.inf.in -- inbox WinUSB, no co-installer sections ---------
if grep -q '^\[USB_Install\.NTx86\.CoInstallers\]' "$L/winusb.inf.in"; then
    awk 'BEGIN{keep=1} /^\[USB_Install\.NTx86\.CoInstallers\]/{keep=0} keep{print}' \
        "$L/winusb.inf.in" > "$L/winusb.inf.in.tmp"
    printf '%s\n' '; (co-installer and SourceDisks sections removed for inbox WinUSB on Windows 10/11 -- SDRLoader patch)' \
        >> "$L/winusb.inf.in.tmp"
    mv "$L/winusb.inf.in.tmp" "$L/winusb.inf.in"
fi

# --- patch 2: winusb.cat.in -- cover only the inf -----------------------------
printf '%s\n' '# inbox WinUSB: no extra binaries to sign (SDRLoader patch)' > "$L/winusb.cat.in"

# --- patch 3: libwdi.c -- WinUSB is always supported (inbox) ------------------
python - "$L/libwdi.c" <<'PY'
import sys
p = sys.argv[1]
s = open(p, encoding="utf-8", errors="surrogateescape").read().split("\n")
old = ["\tcase WDI_WINUSB:", "#if defined(WDK_DIR)", "\t\treturn TRUE;",
       "#else", "\t\treturn FALSE;", "#endif"]
for i in range(len(s) - len(old) + 1):
    if [x.rstrip("\r") for x in s[i:i+len(old)]] == old:
        s[i:i+len(old)] = [
            "\tcase WDI_WINUSB:",
            "\t\t// WinUSB is an inbox driver on Windows 7+, so it is always available even",
            "\t\t// without the WDK co-installers embedded. (SDRLoader patch;",
            "\t\t// upstream returns FALSE unless WDK_DIR is defined at build time.)",
            "\t\treturn TRUE;",
        ]
        open(p, "w", encoding="utf-8", errors="surrogateescape").write("\n".join(s))
        print("  patched wdi_is_driver_supported (WinUSB always supported)")
        break
else:
    if "WinUSB is an inbox driver on Windows 7+" in "\n".join(s):
        print("  libwdi.c already patched")
    else:
        sys.exit("ERROR: could not locate the WDI_WINUSB case to patch")
PY

# --- build: installer_x64.exe -> embedder -> embedded.h -> libwdi.a -----------
echo "  CC   installer_x64.exe"
"$CC" -O2 -D_WIN64 -I "$CFG" -I "$L" "$L/installer.c" -o "$L/installer_x64.exe" \
    -lsetupapi -lnewdev -lole32 -static
echo "  CC   embedder.exe"
"$CC" -O2 -I "$CFG" -I "$L" "$L/embedder.c" -o "$L/embedder.exe"
echo "  GEN  embedded.h"
( cd "$L" && ./embedder.exe embedded.h >/dev/null )
echo "  CC   libwdi objects"
for src in logging tokenizer vid_data pki libwdi_dlg libwdi; do
    "$CC" -O2 -D_WIN64 -I "$CFG" -I "$L" -c "$L/$src.c" -o "$L/$src.o"
done
echo "  AR   libwdi.a"
ar rcs "$L/libwdi.a" "$L"/logging.o "$L"/tokenizer.o "$L"/vid_data.o "$L"/pki.o "$L"/libwdi_dlg.o "$L"/libwdi.o

INC="$(pwd -W)"
echo
echo "libwdi.a built. Configure the project with:"
echo "  -DSDI_WITH_LIBWDI=ON -DLIBWDI_INCLUDE_DIR=\"$INC\" -DLIBWDI_LIBRARY=\"$INC/libwdi.a\""
